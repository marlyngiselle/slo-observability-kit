"""Turn loaded specs into files. Output is deterministic so it can be diffed in CI."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from slokit.dashboard import dashboard
from slokit.models import ServiceSpec
from slokit.policy import policy_markdown
from slokit.rules import count_rules, rule_groups


class _Dumper(yaml.SafeDumper):
    """Block scalars for multi-line PromQL and no anchors, so rule files stay readable."""

    def ignore_aliases(self, data: Any) -> bool:
        return True


def _str_presenter(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_Dumper.add_representer(str, _str_presenter)


def dump_yaml(doc: dict[str, Any]) -> str:
    return yaml.dump(doc, Dumper=_Dumper, sort_keys=False, width=4096, allow_unicode=False)


@dataclass
class Output:
    """Files to write, keyed by path relative to the output directory."""

    files: dict[str, str] = field(default_factory=dict)
    recording_rules: int = 0
    alert_rules: int = 0
    dashboards: int = 0
    slos: int = 0


def render(specs: list[tuple[Path, ServiceSpec]]) -> Output:
    out = Output()
    for path, spec in specs:
        source = path.name
        rules = rule_groups(spec)
        header = f"# Code generated by slokit from {source}. DO NOT EDIT.\n"
        out.files[f"prometheus/rules/{spec.service}.rules.yaml"] = header + dump_yaml(rules)
        out.files[f"grafana/dashboards/{spec.service}.json"] = (
            json.dumps(dashboard(spec), indent=2, sort_keys=False) + "\n"
        )
        out.files[f"policies/{spec.service}.md"] = policy_markdown(spec, source)
        recording, alerts = count_rules(rules)
        out.recording_rules += recording
        out.alert_rules += alerts
        out.dashboards += 1
        out.slos += len(spec.slos)
    return out


def write(output: Output, root: Path) -> list[Path]:
    written: list[Path] = []
    for rel, content in sorted(output.files.items()):
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        written.append(target)
    return written


def diff(output: Output, root: Path) -> list[str]:
    """Paths whose content on disk differs from what would be generated."""
    stale = []
    for rel, content in sorted(output.files.items()):
        target = root / rel
        if not target.is_file() or target.read_text(encoding="utf-8") != content:
            stale.append(rel)
    return stale
