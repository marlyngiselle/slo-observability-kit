"""Error-budget policy, one Markdown page per service."""

from __future__ import annotations

from decimal import Decimal

from slokit.burnrate import DEFAULT_POLICY, Severity, fmt
from slokit.durations import parse_duration
from slokit.models import SLO, ServiceSpec
from slokit.rules import pascal

SLI_MEANING = {
    "availability": "share of requests that succeed",
    "latency": "share of requests served faster than the threshold",
    "freshness": "share of minutes during which the data is fresh enough",
}


def budget_minutes(slo: SLO) -> Decimal:
    minutes = Decimal(parse_duration(slo.window)) / Decimal(60)
    return (slo.error_budget * minutes).quantize(Decimal("0.1"))


def _slo_table(spec: ServiceSpec) -> list[str]:
    rows = [
        "| SLO | SLI | Objective | Window | Error budget | Budget as full outage |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for slo in spec.slos:
        rows.append(
            f"| `{slo.name}` | {SLI_MEANING[slo.sli.type]} | {fmt(slo.objective)}% | "
            f"{slo.window} | {fmt(slo.error_budget * 100)}% | {fmt(budget_minutes(slo))} min |"
        )
    return rows


def _alert_table(spec: ServiceSpec) -> list[str]:
    rows = [
        "| Severity | Burn rate | Long / short window | Budget spent when it fires | Routed to |",
        "| --- | --- | --- | --- | --- |",
    ]
    period = spec.slos[0].window
    for w in DEFAULT_POLICY:
        route = spec.alerting.page if w.severity is Severity.PAGE else spec.alerting.ticket
        target = f"`{route.team}`" + (f" ({route.channel})" if route.channel else "")
        spent = (w.budget_consumed(period) * 100).quantize(Decimal("0.01"))
        rows.append(
            f"| {w.severity.value} | {fmt(w.burn_rate)}x | {w.long_window} / {w.short_window} | "
            f"{fmt(spent)}% of {period} | {target} |"
        )
    return rows


def policy_markdown(spec: ServiceSpec, source: str) -> str:
    alerts = ", ".join(f"`{pascal(spec.service, s.name)}BudgetBurn`" for s in spec.slos)
    lines = [
        f"<!-- Code generated by slokit from {source}. DO NOT EDIT. -->",
        "",
        f"# Error-budget policy: {spec.service}",
        "",
        f"Owned by `{spec.owner}`. The runbook lives at <{spec.alerting.runbook_url}> and "
        f"the dashboard at `/d/slo-{spec.service}`.",
        "",
        "## Objectives",
        "",
        *_slo_table(spec),
        "",
        "Budget as full outage is the time the service could be completely down in one window "
        "and still meet the objective. It is a way to feel the size of the budget, not a "
        "permission to spend it in one go.",
        "",
        "## Alerting",
        "",
        f"{'Alert names are' if len(spec.slos) > 1 else 'The alert is'} {alerts}. "
        "Each page and ticket carries `severity`, `team`, `service` and `slo` labels, "
        "which is what the Alertmanager routing tree matches on.",
        "",
        *_alert_table(spec),
        "",
        "## What we do at each budget level",
        "",
        "| Budget remaining | State | Release policy | Reliability work |",
        "| --- | --- | --- | --- |",
        "| above 50% | Healthy | Ship as usual | Normal backlog |",
        "| 25% to 50% | Watch | Ship, with a rollback plan reviewed for risky changes | "
        "Owner reviews the top error sources weekly |",
        "| 0% to 25% | Constrained | Only low-risk changes and fixes | "
        "At least one engineer on reliability items |",
        "| exhausted | Frozen | Feature freeze, only fixes and security patches | "
        "Team priority until the budget is positive again |",
        "",
        "## Escalation",
        "",
        "1. A page alert opens an incident. The on-call engineer is incident commander until "
        "they hand it over.",
        "2. A ticket alert is triaged within one working day and linked to the weekly "
        "reliability review.",
        "3. If the budget is exhausted twice in a quarter, the owning team presents a "
        "reliability plan at the next service review.",
        "4. Disagreements on a freeze go to the engineering manager of the owning team, who "
        "decides within two working days.",
        "",
        "## Exceptions",
        "",
        "Budget burned by a declared dependency outage or a planned maintenance window stays "
        "on the books, so the SLI keeps telling the truth. The freeze can be waived for it "
        "if the postmortem shows no action is needed on this service.",
        "",
    ]
    return "\n".join(lines)
